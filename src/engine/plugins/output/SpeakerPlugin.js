/**
 * Speaker — Аудиовыход (динамик)
 *
 * Назначение:
 *   Воспроизводит входной сигнал через аудиосистему компьютера (динамики
 *   или наушники). Это финальный блок в цепочке обработки, когда результат
 *   нужно не только увидеть, но и услышать. Используется для прослушивания
 *   синтезированных тонов, демодулированных сигналов, эффектов фильтрации
 *   и любых других звуковых результатов обработки.
 *
 * Принцип работы:
 *   Блок сам по себе является «прозрачным» (passthrough): он возвращает
 *   входной массив отсчётов без изменений (или тишину, если включён mute).
 *   Фактическое воспроизведение звука выполняется в DSPProcessor, который
 *   при обнаружении блока Speaker в графе направляет его выходные данные
 *   в Web Audio API (AudioWorklet или ScriptProcessorNode). Частота
 *   дискретизации определяется настройками симуляции (по умолчанию 48000 Гц).
 *
 *   ВАЖНО: в графе может быть только один блок Speaker. При muted=true
 *   блок выдаёт массив нулей, что приводит к тишине на выходе.
 *
 * Параметры:
 *   - muted (boolean, по умолчанию false) — отключение звука.
 *     При true блок выдаёт тишину (Float32Array, заполненный нулями).
 *     Полезно для временного отключения воспроизведения без разрыва
 *     соединений в графе.
 *
 * Вход:  real (Float32Array — отсчёты вещественного сигнала, диапазон [-1, +1])
 * Выход: null (терминальный блок, данные направляются в аудиосистему)
 *
 * Примеры использования:
 *
 *   1. Воспроизведение тона:
 *      Sine(440) → Speaker
 *      В динамиках звучит нота «ля» первой октавы (440 Гц) — стандартный
 *      камертон. Рекомендуется начинать с малой громкости!
 *
 *   2. Прослушивание результата фильтрации:
 *      AudioFile(music.wav) → NotchFIR(50 Гц) → Speaker
 *      Воспроизводит аудиофайл с подавленной сетевой наводкой 50 Гц.
 *
 *   3. Демодуляция и прослушивание:
 *      AMFMPMModulator(FM) → FrequencyDiscriminator → Speaker
 *      Восстанавливает и воспроизводит модулирующий сигнал из ЧМ-сигнала.
 *
 * Предупреждение:
 *   Амплитуда сигнала должна быть в пределах [-1, +1]. Значения за пределами
 *   этого диапазона вызовут клиппинг (искажения). При необходимости используйте
 *   блок Gain для масштабирования сигнала перед подачей на Speaker.
 */
export default {
    type: 'Динамик',
    id: 'speaker',
    icon: 'dsp-speaker',
    description: 'Аудио выход',
    group: 'output',
    signals: { input: 'real', output: null },
    defaultParams: {
        muted: false
    },
    processor: {
        process(inputs, params, chunkSize) {
            const output = inputs[0] || new Float32Array(chunkSize);
            if (params.muted) {
                return new Float32Array(chunkSize);
            }
            return output;
        }
    }
};
