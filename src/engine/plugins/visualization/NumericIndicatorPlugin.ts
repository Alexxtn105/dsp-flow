/**
 * Numeric Indicator — Числовой индикатор вещественного сигнала
 *
 * Назначение:
 *   Отображает мгновенное числовое значение вещественного (real) сигнала.
 *   Это простейший блок визуализации — аналог цифрового вольтметра:
 *   показывает последний отсчёт сигнала в виде числа. Полезен для контроля
 *   постоянных значений (DC), уровней сигнала, результатов вычислений,
 *   а также для отладки — чтобы убедиться, что значение на выходе блока
 *   соответствует ожиданиям.
 *
 * Принцип работы:
 *   Блок является «прозрачным» (passthrough): принимает входной Float32Array
 *   без изменений и передаёт его в компонент визуализации NumericIndicatorView,
 *   который отображает значение последнего отсчёта в числовом формате.
 *
 * Параметры:
 *   Нет настраиваемых параметров.
 *
 * Вход:  real (Float32Array — отсчёты вещественного сигнала)
 * Выход: null (блок визуализации, данные передаются в NumericIndicatorView)
 *
 * Примеры использования:
 *
 *   1. Отображение константы:
 *      Constant(3.14) → NumericIndicator
 *      Индикатор показывает «3.14» — удобно для проверки правильности
 *      настройки блока Constant.
 *
 *   2. Контроль уровня сигнала:
 *      Sine(1000) → AmplitudeDetector → NumericIndicator
 *      Показывает текущую амплитуду синусоиды (≈1.0 при единичной амплитуде).
 *
 *   3. Отладка вычислений:
 *      Signal → Gain(коэффициент=0.5) → NumericIndicator
 *      Позволяет убедиться, что блок Gain корректно масштабирует сигнал.
 */
export default {
    type: 'Числовой индикатор',
    id: 'numeric-indicator',
    icon: 'dsp-numeric',
    description: 'Отображает мгновенное значение действительного сигнала',
    group: 'visualization',
    signals: { input: 'real', output: null } as const,
    defaultParams: {},
    processor: {
        process(inputs: (Float32Array | null)[], _params: Record<string, unknown>, chunkSize: number) {
            return inputs[0] || new Float32Array(chunkSize);
        }
    }
};
