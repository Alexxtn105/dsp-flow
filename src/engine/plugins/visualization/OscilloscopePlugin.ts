/**
 * Oscilloscope — Четырёхканальный осциллограф
 *
 * Назначение:
 *   Осциллограф — основной инструмент визуализации сигналов во временной области.
 *   Показывает, как значение сигнала (амплитуда) изменяется во времени.
 *   Этот блок поддерживает до 4 независимых каналов, что позволяет наблюдать
 *   несколько сигналов одновременно на одном экране — например, входной и выходной
 *   сигналы фильтра, или I- и Q-компоненты, или сигнал до и после обработки.
 *
 * Принцип работы:
 *   Блок является «прозрачным» (passthrough): он не изменяет входные данные,
 *   а просто передаёт массивы отсчётов из всех подключённых каналов
 *   в компонент визуализации OscilloscopeView. Данные упаковываются в объект
 *   {channels: [ch1, ch2, ch3, ch4]}, где каждый канал — Float32Array или null
 *   (если вход не подключён).
 *
 * Параметры:
 *   - timeWindow (int, по умолчанию 10) — ширина временного окна отображения
 *     в миллисекундах. Определяет, сколько данных видно на экране.
 *     Меньшее значение → больше деталей формы сигнала.
 *     Большее значение → видна общая огибающая, но мелкие детали теряются.
 *
 * Вход:  4× real (до 4 каналов: «Канал 1», «Канал 2», «Канал 3», «Канал 4»)
 * Выход: null (блок визуализации, данные передаются в OscilloscopeView)
 *
 * Примеры использования:
 *
 *   1. Просмотр формы сигнала:
 *      Sine(1000) → Oscilloscope (Канал 1)
 *      На экране видна классическая синусоида с периодом 1 мс.
 *
 *   2. Сравнение входа и выхода фильтра:
 *      Sine(1000) + NoiseGenerator → Summer → Oscilloscope (Канал 1)
 *      Summer → LowpassFIR(2000) → Oscilloscope (Канал 2)
 *      На Канале 1 — зашумлённый сигнал, на Канале 2 — очищенный фильтром.
 *
 *   3. Наблюдение за биениями:
 *      Sine(1000) → Oscilloscope (Канал 1)
 *      Sine(1050) → Oscilloscope (Канал 2)
 *      Sine(1000) → Summer ← Sine(1050), Summer → Oscilloscope (Канал 3)
 *      На Канале 3 видны биения с частотой 50 Гц (разность частот).
 */
export default {
    type: 'Осциллограф',
    id: 'oscilloscope',
    icon: 'dsp-oscilloscope',
    description: 'Визуализация сигнала (4 канала)',
    group: 'visualization',
    signals: {
        input: 'real',
        output: null,
        inputsCount: 4,
        inputLabels: ['Канал 1', 'Канал 2', 'Канал 3', 'Канал 4']
    } as const,
    defaultParams: {
        timeWindow: 10,
    },
    processor: {
        process(inputs: (Float32Array | null)[], _params: Record<string, unknown>, _chunkSize: number) {
            const channels: (Float32Array | null)[] = [];
            for (let i = 0; i < 4; i++) {
                channels.push(inputs[i] || null);
            }
            return { channels };
        }
    }
};
