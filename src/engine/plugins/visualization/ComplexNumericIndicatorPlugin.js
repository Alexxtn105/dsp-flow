/**
 * Complex Numeric Indicator — Числовой индикатор комплексного сигнала
 *
 * Назначение:
 *   Отображает мгновенное значение комплексного сигнала в формате Re + jIm.
 *   Комплексный сигнал состоит из двух компонент: действительной (Re, I — in-phase)
 *   и мнимой (Im, Q — quadrature). Этот блок показывает обе компоненты
 *   одновременно, что удобно для отладки комплексной арифметики, проверки
 *   работы модуляторов/демодуляторов и контроля фазовых соотношений.
 *
 * Принцип работы:
 *   Блок является «прозрачным» (passthrough) для комплексного сигнала:
 *   принимает interleaved Float32Array [I0, Q0, I1, Q1, ...] без изменений
 *   и передаёт его в компонент визуализации, который отображает последнюю
 *   пару (I, Q) в формате «Re + jIm» (например, «0.707 + j0.707»).
 *
 * Параметры:
 *   Нет настраиваемых параметров.
 *
 * Вход:  complex (interleaved Float32Array [I0, Q0, I1, Q1, ...])
 * Выход: null (блок визуализации, данные передаются в визуализатор)
 *
 * Примеры использования:
 *
 *   1. Просмотр комплексной экспоненты:
 *      RefSine(1000) → ComplexNumericIndicator
 *      Показывает текущие значения I и Q, например «0.707 + j0.707»
 *      (что соответствует фазе 45° на единичной окружности).
 *
 *   2. Проверка комплексной арифметики:
 *      ComplexComposer(Re=3, Im=4) → ComplexNumericIndicator
 *      Индикатор показывает «3.000 + j4.000» — удобно для верификации.
 *
 *   3. Отладка демодулятора:
 *      PSKModulator(QPSK) → PLL → ComplexNumericIndicator
 *      Значения I и Q должны группироваться около ±0.707 для QPSK —
 *      если нет, значит синхронизация работает некорректно.
 */
export default {
    type: 'Комплексный числовой индикатор',
    id: 'complex-numeric-indicator',
    icon: 'dsp-complex-numeric',
    description: 'Отображает мгновенное значение комплексного сигнала (Re + jIm)',
    group: 'visualization',
    signals: { input: 'complex', output: null },
    defaultParams: {},
    processor: {
        process(inputs, params, chunkSize) {
            return inputs[0] || new Float32Array(chunkSize * 2);
        }
    }
};
