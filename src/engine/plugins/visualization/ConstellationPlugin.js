/**
 * Constellation — Диаграмма фазового созвездия (I/Q)
 *
 * Назначение:
 *   Диаграмма созвездия (constellation diagram) — это способ визуализации
 *   цифрового модулированного сигнала. Каждый передаваемый символ кодируется
 *   двумя числами: I (синфазная компонента, по горизонтали) и Q (квадратурная,
 *   по вертикали). На диаграмме каждый символ отображается как точка на
 *   плоскости I/Q.
 *
 *   Для идеального сигнала точки группируются в заранее определённых позициях:
 *   - BPSK: 2 точки на горизонтальной оси (±1)
 *   - QPSK: 4 точки по углам квадрата (±1 ± j1)
 *   - 8-PSK: 8 точек на окружности
 *   - 16-QAM: 16 точек в виде сетки 4×4
 *
 *   В реальных условиях шум, искажения и ошибки синхронизации «размазывают»
 *   точки вокруг идеальных позиций. По степени размытия можно оценить качество
 *   канала связи и корректность работы демодулятора.
 *
 * Принцип работы:
 *   Блок является «прозрачным» (passthrough) для комплексного сигнала:
 *   принимает interleaved Float32Array [I0, Q0, I1, Q1, ...] и передаёт его
 *   без изменений в компонент визуализации ConstellationView, который
 *   отрисовывает каждую пару (I, Q) как точку на двумерной плоскости.
 *
 * Параметры:
 *   - symbolRate (int, по умолчанию 1000) — символьная скорость в бодах.
 *     Используется визуализатором для определения моментов стробирования
 *     (какие именно отсчёты являются «символами»).
 *   - constellation (string, по умолчанию 'QPSK') — тип созвездия.
 *     Варианты: 'BPSK', 'QPSK', '8PSK', '16QAM'.
 *     Определяет отображение эталонных точек (reference grid) на диаграмме.
 *   - eyeDiagram (boolean, по умолчанию true) — отображение глазковой диаграммы.
 *     Глазковая диаграмма показывает наложенные друг на друга символьные
 *     интервалы — «раскрытие глаза» свидетельствует о хорошем качестве сигнала.
 *
 * Вход:  complex (interleaved Float32Array [I0, Q0, I1, Q1, ...])
 * Выход: null (блок визуализации, данные передаются в ConstellationView)
 *
 * Примеры использования:
 *
 *   1. Визуализация QPSK-модуляции:
 *      PSKModulator(QPSK) → Constellation
 *      На диаграмме видны 4 чёткие точки в позициях (±0.707, ±0.707) —
 *      это идеальное созвездие QPSK без шума.
 *
 *   2. Оценка влияния шума:
 *      PSKModulator(QPSK) → [канал с шумом] → Constellation
 *      Точки «размазываются» вокруг идеальных позиций. Чем сильнее шум,
 *      тем больше «облака» вокруг каждой точки.
 *
 *   3. Проверка синхронизации:
 *      PSKModulator(8PSK, sps=4) → TimingRecovery(sps=4) → PLL → Constellation
 *      Если синхронизация работает корректно, на диаграмме видны 8 чётких
 *      точек на окружности. Без PLL точки вращаются (фазовый сдвиг).
 */
export default {
    type: 'Фазовое созвездие',
    id: 'constellation',
    icon: 'dsp-constellation',
    description: 'Фазовое созвездие',
    group: 'visualization',
    signals: { input: 'complex', output: null },
    defaultParams: {
        symbolRate: 1000,
        constellation: 'QPSK',
        eyeDiagram: true,
    },
    processor: {
        process(inputs, params, chunkSize) {
            return inputs[0] || new Float32Array(chunkSize * 2);
        }
    }
};
