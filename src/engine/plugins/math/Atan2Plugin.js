/**
 * Арктангенс двух аргументов (Atan2) — Вычисление угла по двум компонентам
 *
 * Назначение:
 *   Вычисляет угол (фазу) в радианах по двум действительным входам Y и X
 *   с помощью функции atan2(Y, X). В отличие от обычного арктангенса (atan),
 *   функция atan2 корректно определяет квадрант и возвращает значение в
 *   полном диапазоне [-π, π]. Это необходимо для вычисления мгновенной фазы
 *   сигнала, когда синфазная (I) и квадратурная (Q) компоненты представлены
 *   отдельными действительными сигналами.
 *
 * Алгоритм:
 *   y[n] = atan2(Y[n], X[n])
 *   Результат в радианах: от -π (-180°) до +π (+180°).
 *   При Y=0 и X=0 результат равен 0.
 *
 * Параметры:
 *   Нет параметров.
 *
 * Входы:
 *   - Верхний вход (input 0): Y — вертикальная (мнимая) компонента
 *   - Нижний вход (input 1): X — горизонтальная (действительная) компонента
 * Вход:  real (2 входа, Float32Array)
 * Выход: real (Float32Array, значения в радианах [-π, π])
 *
 * Примеры использования:
 *
 *   1. Вычисление фазы из I/Q компонент:
 *      RealPart(сигнал) → [X], ImagPart(сигнал) → [Y] → Atan2 → Oscilloscope
 *      Эквивалент ComplexPhase, но для сигналов, разделённых на
 *      отдельные действительные потоки.
 *
 *   2. Детектирование направления:
 *      Sine(f) → [Y], Cosine(f) → [X] → Atan2 → Oscilloscope
 *      На выходе — линейно нарастающая фаза (пилообразный сигнал)
 *      от -π до π, что соответствует вращению вектора.
 *
 *   3. Фазовая демодуляция:
 *      I-канал → [X], Q-канал → [Y] → Atan2 → дифференцирование
 *      Извлечение мгновенной фазы для последующего вычисления
 *      мгновенной частоты (производная фазы по времени).
 */
export default {
    type: 'Арктангенс',
    id: 'atan2',
    icon: 'dsp-atan2',
    description: 'Арктангенс (atan2). Верхний вход — Y, нижний — X. Выход в радианах [−π, π]',
    group: 'math-blocks',
    signals: { input: 'real', output: 'real', inputsCount: 2 },
    defaultParams: {},
    processor: {
        process(inputs, params, chunkSize) {
            const y = inputs[0];
            const x = inputs[1];
            const output = new Float32Array(chunkSize);

            for (let i = 0; i < chunkSize; i++) {
                const yi = y && i < y.length ? y[i] : 0;
                const xi = x && i < x.length ? x[i] : 0;
                output[i] = Math.atan2(yi, xi);
            }

            return output;
        }
    }
};
