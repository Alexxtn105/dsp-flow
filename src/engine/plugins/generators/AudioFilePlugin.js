/**
 * Audio File — Источник аудиосигнала из WAV-файла
 *
 * Назначение:
 *   Позволяет загрузить WAV-файл и использовать его как источник реального сигнала
 *   в графе обработки. Это необходимо для работы с реальными записями: анализ речи,
 *   музыки, радиосигналов, тестирование фильтров и детекторов на реальных данных
 *   вместо синтетических генераторов.
 *
 * Архитектура:
 *   Данный плагин является «заглушкой» (placeholder). Фактическое чтение WAV-файла
 *   и подача аудиоданных в граф выполняется в DSPProcessor, который перехватывает
 *   обработку этого блока и подставляет данные из загруженного файла. Если по
 *   какой-то причине process() вызывается напрямую (например, файл не загружен),
 *   возвращается тишина (массив нулей).
 *
 *   Поддерживаемый формат: WAV (PCM). Чтение и декодирование выполняет WavFileService.
 *   Стерео файлы микшируются в моно. Частота дискретизации приводится к sampleRate
 *   симуляции.
 *
 * Параметры:
 *   - wavFile (File | null, по умолчанию null) — объект File, выбранный пользователем
 *     через диалог загрузки. Значение null означает, что файл не загружен.
 *
 * Вход:  нет (автономный источник)
 * Выход: real (Float32Array длиной chunkSize, данные из WAV-файла или тишина)
 *
 * Примеры использования:
 *
 *   1. Анализ спектра аудиозаписи:
 *      AudioFile(speech.wav) → SpectrumAnalyzer
 *      Загруженная запись речи отображается на спектроанализаторе.
 *
 *   2. Фильтрация аудиосигнала:
 *      AudioFile(music.wav) → BandpassFIR(200–3400 Гц) → Speaker
 *      Музыка фильтруется полосовым фильтром (телефонная полоса) и воспроизводится.
 *
 *   3. Водопадная диаграмма:
 *      AudioFile(radio.wav) → Waterfall
 *      Визуализация изменения спектра радиосигнала во времени.
 */

export default {
    type: 'Audio File',
    id: 'audio-file',
    icon: 'dsp-audio-file',
    description: 'Источник аудиофайла',
    group: 'generators',
    signals: { input: null, output: 'real' },
    defaultParams: {
        wavFile: null,
    },
    processor: {
        process(inputs, params, chunkSize) {
            // Этот блок обрабатывается в DSPProcessor (читает файл)
            // Если вызван process, возвращаем тишину
            return new Float32Array(chunkSize);
        }
    }
};
