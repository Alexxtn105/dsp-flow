/**
 * Константа — Источник постоянного (DC) сигнала
 *
 * Назначение:
 *   Генерирует сигнал с постоянным значением на каждом отсчёте. Применяется как:
 *   - DC-смещение (bias) — добавление постоянной составляющей к сигналу через Summer;
 *   - управляющий сигнал — фиксированное значение частоты для NCO (RefSine/RefCosine);
 *   - масштабирующий коэффициент — умножение сигнала на константу через Multiplier;
 *   - пороговый уровень — задание уровня для блока Threshold;
 *   - тестовый сигнал — проверка линейности и смещения в цепочке обработки.
 *
 * Алгоритм:
 *   Тривиальный: выходной массив Float32Array заполняется одним и тем же значением
 *   через метод fill(). Никаких состояний между чанками не хранится (хотя Map
 *   состояний присутствует для совместимости с интерфейсом плагина).
 *
 * Параметры:
 *   - value (float, по умолчанию 1.0) — значение константы.
 *     Допустим любой float: положительные, отрицательные, нулевые значения.
 *     Типичные значения: 0.0 (тишина/ноль), 1.0 (единичный коэффициент),
 *     1000 (частота 1 кГц для NCO), −0.5 (отрицательное смещение).
 *
 * Вход:  нет (автономный источник)
 * Выход: real (Float32Array длиной chunkSize, заполненный значением value)
 *
 * Примеры использования:
 *
 *   1. Задание частоты для NCO:
 *      Constant(5000) → RefSine(вход частоты)
 *      NCO будет генерировать сигнал на фиксированной частоте 5 кГц.
 *      Эквивалентно параметру frequency=5000, но позволяет менять частоту
 *      без перенастройки блока.
 *
 *   2. DC-смещение сигнала:
 *      Sine(1000 Гц) + Constant(0.5) → Summer → Oscilloscope
 *      Синусоида смещается вверх на 0.5, колеблясь в диапазоне [−0.5, 1.5].
 *
 *   3. Масштабирование (ручной Gain):
 *      Входной сигнал → Multiplier ← Constant(0.1)
 *      Сигнал ослабляется в 10 раз.
 */

import type { PluginDefinition } from '../../types';

interface ConstantState {
    // Пустое состояние для совместимости с интерфейсом плагина
}

export default {
    type: 'Константа',
    id: 'constant',
    icon: 'dsp-constant',
    description: 'Постоянное значение',
    group: 'generators',
    signals: { input: null, output: 'real' } as const,
    defaultParams: {
        value: 1.0,
    },
    processor: {
        states: new Map<string, ConstantState>(),
        clearStates() { this.states.clear(); },

        process(inputs: (Float32Array | null)[], params: Record<string, unknown>, chunkSize: number): Float32Array {
            const output = new Float32Array(chunkSize);
            const val = params.value ?? 1.0;
            output.fill(val as number);
            return output;
        }
    }
};
