/**
 * Полосовой КИХ-фильтр — пропускание заданной полосы частот
 *
 * Назначение:
 *   Пропускает сигнал только в заданном диапазоне частот (от lowCutoff
 *   до highCutoff), подавляя всё, что ниже и выше этой полосы.
 *   Полосовой фильтр — один из базовых инструментов ЦОС: он позволяет
 *   выделить полезный сигнал из смеси, ограничить полосу перед демодуляцией,
 *   разделить каналы в многоканальной системе и т.п.
 *
 * Алгоритм:
 *   Используется метод оконного sinc-фильтра (windowed sinc). Полосовой
 *   фильтр строится как разность двух ФНЧ: один с частотой среза highCutoff,
 *   другой — lowCutoff. Коэффициенты умножаются на выбранную оконную функцию
 *   для управления уровнем боковых лепестков. Реализация через фабрику
 *   createFIRProcessor('bandpass') из FIRFilterPlugin.
 *
 * Параметры:
 *   - order (int, по умолчанию 64) — порядок фильтра (количество
 *     коэффициентов). Больший порядок → более крутые скаты полосы
 *     пропускания, но увеличивает задержку. Рекомендуемый диапазон: 16–512.
 *   - lowCutoff (float, по умолчанию 1000) — нижняя граница полосы
 *     пропускания в Гц. Частоты ниже этого значения подавляются.
 *   - highCutoff (float, по умолчанию 3000) — верхняя граница полосы
 *     пропускания в Гц. Частоты выше этого значения подавляются.
 *     Должно выполняться: lowCutoff < highCutoff < sampleRate/2.
 *   - windowFunction (string, по умолчанию 'hamming') — оконная функция.
 *     Варианты: 'rectangular', 'hamming', 'hanning', 'blackman',
 *     'blackman-harris', 'nuttall', 'flattop'.
 *
 * Вход:  real (Float32Array)
 * Выход: real (Float32Array) — сигнал, содержащий только полосу [lowCutoff, highCutoff]
 *
 * Примеры использования:
 *
 *   1. Выделение речевого диапазона:
 *      AudioFile → BandpassFIR(300Hz–3400Hz) → Speaker
 *      Классический телефонный диапазон: убирает низкочастотный гул
 *      и высокочастотный шум, оставляя разборчивую речь.
 *
 *   2. Фильтрация перед демодуляцией:
 *      Sine(2000) + NoiseGenerator → Summer → BandpassFIR(1500–2500Hz) → Oscilloscope
 *      Полосовой фильтр выделяет сигнал 2 кГц из шума.
 *
 *   3. Анализ спектра в полосе:
 *      AudioFile → BandpassFIR(1000–3000Hz) → SpectrumAnalyzer
 *      На спектроанализаторе видны только компоненты в полосе 1–3 кГц.
 */
import { createFIRProcessor } from './FIRFilterPlugin.js';

export default {
    type: 'Полосовой КИХ-фильтр',
    id: 'bandpass-fir-filter',
    icon: 'dsp-bandpass',
    description: 'Полосовой КИХ-фильтр',
    group: 'filters',
    signals: { input: 'real', output: 'real' },
    defaultParams: {
        order: 64,
        lowCutoff: 1000,
        highCutoff: 3000,
        windowFunction: 'hamming',
    },
    processor: createFIRProcessor('bandpass')
};
